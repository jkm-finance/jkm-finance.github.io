// UI strings (KO / EN / JA) and item text translation lookup (SPEC §14, DATA_MODEL §3.3).
import trKo from '../data/tr_ko.js';
import trJa from '../data/tr_ja.js';

const TR = { ko: trKo, ja: trJa };
const LANGS = ['ko', 'en', 'ja'];
let lang = (() => { try { const l = localStorage.getItem('jkmcsa.lang'); return LANGS.includes(l) ? l : 'ko'; } catch { return 'ko'; } })();

export function getLang() { return lang; }
export function setLang(l) { if (!LANGS.includes(l)) return; lang = l; try { localStorage.setItem('jkmcsa.lang', l); } catch { /* per-viewer convenience only */ } }

// Item text in the chosen language. Focus items whose text equals a Full item reuse its translation.
export function itemText(meta, l = lang) {
  if (l === 'en' || !TR[l]) return { ws: meta.ws, ts: meta.ts, translated: false };
  const d = TR[l][meta.id] || (meta.fullRef ? TR[l][meta.fullRef] : null);
  if (!d || !d.ws) return { ws: meta.ws, ts: meta.ts, translated: false };
  return { ws: d.ws, ts: meta.ts ? d.ts || meta.ts : null, translated: true };
}

export function t(key, vars) {
  const row = D[key];
  let s = row ? row[LANGS.indexOf(lang)] || row[1] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return s;
}

export function missingKeys() {
  return Object.entries(D).filter(([, r]) => r.length !== 3 || r.some((x) => !x)).map(([k]) => k);
}

